export type CurrencyCode = keyof typeof CURRENCIES;

export const CURRENCY_CODES = Object.keys(CURRENCIES) as CurrencyCode[];

/** Shown first in pickers. */
export const COMMON_CURRENCIES: CurrencyCode[] = ["USD", "EUR", "GBP", "CAD", "AUD", "JPY", "CNY", "INR", "MXN", "CHF", "NZD", "SGD"];

export function isCurrencyCode(code: string): code is CurrencyCode {
  return Object.hasOwn(CURRENCIES, code);
}

/** "Japanese Yen" for "JPY"; the code itself for one not in the list. */
export function currencyName(code: string): string {
  return isCurrencyCode(code) ? CURRENCIES[code] : code;
}

/** Accents removed, so "Córdoba" sorts with the Cs the same way on every machine. */
const sortKey = (name: string) => name.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase();

/** Every currency except the common ones, sorted by name. */
export const OTHER_CURRENCIES: CurrencyCode[] = CURRENCY_CODES.filter((c) => !COMMON_CURRENCIES.includes(c)).sort((a, b) => {
  const [x, y] = [sortKey(currencyName(a)), sortKey(currencyName(b))];
  return x < y ? -1 : x > y ? 1 : 0;
});
